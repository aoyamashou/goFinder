// gen.swift writes ../table.go: the first letter of the Mandarin reading of
// every character from U+4E00 to U+9FFF, as macOS's CFStringTransform reads
// it, "0" for those it has none for. Run from internal/pinyin:
//
//	swift gen/gen.swift > table.go
import Foundation

var out = ""
for u in 0x4E00...0x9FFF {
    let s = NSMutableString(string: String(UnicodeScalar(u)!))
    var ch: Character = "0"
    if CFStringTransform(s, nil, kCFStringTransformMandarinLatin, false),
       CFStringTransform(s, nil, kCFStringTransformStripDiacritics, false),
       let f = (s as String).lowercased().first, f.isASCII, f.isLetter {
        ch = f
    }
    out.append(ch)
}
print("// Code generated by gen/gen.swift; DO NOT EDIT.\n")
print("package pinyin\n")
print("// table is the first letter of the reading of U+4E00+i, '0' for none.")
print("const table = \"\(out)\"")
